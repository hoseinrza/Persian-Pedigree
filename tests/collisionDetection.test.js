import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  computePedigreeLayout,
  detectCollisions,
  resolveCollisions,
  getRequiredSeparation,
  DEFAULTS,
} from '../src/pedigreeLayout.js';

describe('Collision Detection & Dynamic Spacing Engine', () => {
  it('correctly calculates required relationship-specific separations', () => {
    const people = {
      p1: { id: 'p1', sex: 'male', spouseIds: ['p2'], childIds: [] },
      p2: { id: 'p2', sex: 'female', spouseIds: ['p1'], childIds: [] },
      p3: { id: 'p3', sex: 'male', twinType: 'identical', twinGroupId: 'tg1', spouseIds: [], childIds: [] },
      p4: { id: 'p4', sex: 'male', twinType: 'identical', twinGroupId: 'tg1', spouseIds: [], childIds: [] },
      p5: { id: 'p5', sex: 'female', spouseIds: [], childIds: [] },
    };

    // Spouses must have coupleGap
    assert.equal(getRequiredSeparation('p1', 'p2', people, DEFAULTS), DEFAULTS.coupleGap);
    // Identical twins must have twinGap
    assert.equal(getRequiredSeparation('p3', 'p4', people, DEFAULTS), DEFAULTS.twinGap);
    // General unrelated / siblings must have nodeGap
    assert.equal(getRequiredSeparation('p1', 'p5', people, DEFAULTS), DEFAULTS.nodeGap);
  });

  it('detects clearance violations when nodes are placed too close', () => {
    const people = {
      n1: { id: 'n1', sex: 'male', spouseIds: [], childIds: [] },
      n2: { id: 'n2', sex: 'female', spouseIds: [], childIds: [] },
    };
    const layerOf = { n1: 0, n2: 0 };
    // Place them 40px apart, which is less than DEFAULTS.nodeGap (104px)
    const nodes = {
      n1: { x: 100, y: 0 },
      n2: { x: 140, y: 0 },
    };

    const result = detectCollisions(nodes, people, layerOf, DEFAULTS);
    assert.equal(result.hasCollisions, true);
    assert.equal(result.totalCount, 1);
    assert.equal(result.collisions[0].id1, 'n1');
    assert.equal(result.collisions[0].id2, 'n2');
    assert.ok(result.collisions[0].overlap > 0, 'Overlap should be positive');
  });

  it('automatically resolves collisions and adjusts spacing without overlaps', () => {
    const people = {
      n1: { id: 'n1', sex: 'male', spouseIds: [], childIds: [] },
      n2: { id: 'n2', sex: 'female', spouseIds: [], childIds: [] },
      n3: { id: 'n3', sex: 'male', spouseIds: [], childIds: [] },
    };
    const families = new Map();
    const layerOf = { n1: 0, n2: 0, n3: 0 };

    // Intentionally overlap all 3 nodes on the same layer
    const nodes = {
      n1: { x: 50, y: 0 },
      n2: { x: 60, y: 0 },
      n3: { x: 70, y: 0 },
    };

    const report = resolveCollisions(nodes, people, families, layerOf, DEFAULTS);
    assert.equal(report.resolved, true, 'Collisions should be resolved');
    assert.equal(report.finalCollisions, 0, '0 collisions should remain');

    // Verify distance between adjacent nodes is >= DEFAULTS.nodeGap
    assert.ok(nodes.n2.x - nodes.n1.x >= DEFAULTS.nodeGap - 0.01, 'n2 and n1 should be spaced by at least nodeGap');
    assert.ok(nodes.n3.x - nodes.n2.x >= DEFAULTS.nodeGap - 0.01, 'n3 and n2 should be spaced by at least nodeGap');
  });

  it('automatically shifts descendant subtrees when a parent is pushed by collision resolution', () => {
    const people = {
      p1: { id: 'p1', sex: 'male', spouseIds: [], childIds: [] },
      p2: { id: 'p2', sex: 'male', spouseIds: ['sp2'], childIds: ['c2'] },
      sp2: { id: 'sp2', sex: 'female', spouseIds: ['p2'], childIds: ['c2'] },
      c2: { id: 'c2', sex: 'female', fatherId: 'p2', motherId: 'sp2', spouseIds: [], childIds: [] },
    };
    const families = new Map([
      ['F:p2+sp2', { id: 'F:p2+sp2', parents: ['p2', 'sp2'], children: ['c2'] }],
    ]);
    const layerOf = { p1: 0, p2: 0, sp2: 0, c2: 1 };

    // Force p1 and p2 into collision
    const nodes = {
      p1: { x: 0, y: 0 },
      p2: { x: 10, y: 0 },
      sp2: { x: 90, y: 0 },
      c2: { x: 50, y: 155 },
    };

    const initialC2X = nodes.c2.x;
    const report = resolveCollisions(nodes, people, families, layerOf, DEFAULTS);
    assert.equal(report.resolved, true);

    // c2 should have moved right along with its parents p2/sp2 to maintain vertical descent integrity
    assert.ok(nodes.c2.x > initialC2X, 'Descendant c2 should be shifted along with its parent branch');
    assert.ok(nodes.p2.x - nodes.p1.x >= DEFAULTS.nodeGap - 0.01);
  });

  it('guarantees zero collisions in dense complex pedigrees generated by layout engine', () => {
    // Dense family: 2 married couples in the same generation, each with 5 children
    const people = {
      root_m: { id: 'root_m', sex: 'male', spouseIds: ['root_f'], childIds: ['p1', 'p2'] },
      root_f: { id: 'root_f', sex: 'female', spouseIds: ['root_m'], childIds: ['p1', 'p2'] },

      p1: { id: 'p1', sex: 'male', fatherId: 'root_m', motherId: 'root_f', spouseIds: ['sp1'], childIds: ['c1_1', 'c1_2', 'c1_3', 'c1_4', 'c1_5'] },
      sp1: { id: 'sp1', sex: 'female', spouseIds: ['p1'], childIds: ['c1_1', 'c1_2', 'c1_3', 'c1_4', 'c1_5'] },

      p2: { id: 'p2', sex: 'male', fatherId: 'root_m', motherId: 'root_f', spouseIds: ['sp2'], childIds: ['c2_1', 'c2_2', 'c2_3', 'c2_4', 'c2_5'] },
      sp2: { id: 'sp2', sex: 'female', spouseIds: ['p2'], childIds: ['c2_1', 'c2_2', 'c2_3', 'c2_4', 'c2_5'] },
    };

    for (let i = 1; i <= 5; i++) {
      const c1Id = `c1_${i}`;
      const c2Id = `c2_${i}`;
      people[c1Id] = { id: c1Id, sex: i % 2 === 0 ? 'female' : 'male', fatherId: 'p1', motherId: 'sp1', spouseIds: [], childIds: [] };
      people[c2Id] = { id: c2Id, sex: i % 2 === 0 ? 'male' : 'female', fatherId: 'p2', motherId: 'sp2', spouseIds: [], childIds: [] };
    }

    const layout = computePedigreeLayout({ people });
    assert.ok(layout.collisions, 'Layout result should include collision diagnostics');
    assert.equal(layout.collisions.finalCollisions, 0, 'No collisions should remain in dense layout');

    // Run direct collision check across all nodes
    const postCheck = detectCollisions(layout.nodes, people, layout.generations, DEFAULTS);
    assert.equal(postCheck.hasCollisions, false, 'Direct postCheck must find zero collisions');
  });

  it('computes debug bounding boxes for all nodes and connection lines', () => {
    const people = {
      p1: { id: 'p1', sex: 'male', spouseIds: ['p2'], childIds: ['c1'] },
      p2: { id: 'p2', sex: 'female', spouseIds: ['p1'], childIds: ['c1'] },
      c1: { id: 'c1', sex: 'female', fatherId: 'p1', motherId: 'p2', spouseIds: [], childIds: [] },
    };

    const layout = computePedigreeLayout({ people });
    assert.ok(layout.debugBoxes, 'Layout should contain debugBoxes');
    assert.equal(layout.debugBoxes.nodes.length, 3, 'Should generate bounding boxes for all 3 nodes');

    // Verify node bounding box structure
    const p1Box = layout.debugBoxes.nodes.find((b) => b.id === 'p1');
    assert.ok(p1Box);
    assert.ok(p1Box.width > 0 && p1Box.height > 0);
    assert.ok(p1Box.clearanceBox.width >= DEFAULTS.coupleGap);

    // Verify connector bounding boxes
    assert.ok(layout.debugBoxes.connectors.length >= 3, 'Should generate boxes for mating, drop, and child link');
    const matingBox = layout.debugBoxes.connectors.find((c) => c.type === 'mating');
    assert.ok(matingBox);
    assert.ok(matingBox.width > 0 && matingBox.height > 0);
  });
});
